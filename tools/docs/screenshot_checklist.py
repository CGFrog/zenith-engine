"""Regenerates docs/guide/SCREENSHOTS.md from the screenshot callouts in docs/.

A callout is a blockquote line of the form

    > 📷 **Screenshot needed — `ID`:** *What to capture.*

Run from the repository root:  python tools/docs/screenshot_checklist.py
Pass --check to fail (exit 1) when the checklist is out of date, e.g. in CI.
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
DOCS = ROOT / "docs"
OUTPUT = DOCS / "guide" / "SCREENSHOTS.md"
CALLOUT = re.compile(r"^> 📷 \*\*Screenshot needed — `([A-Z0-9-]+)`:\*\* \*(.+?)\*?$")


def collect():
    shots = []
    for path in sorted(DOCS.rglob("*.md")):
        if path == OUTPUT:
            continue
        lines = path.read_text(encoding="utf-8").splitlines()
        in_code = False
        for index, line in enumerate(lines):
            if line.lstrip().startswith("```"):
                in_code = not in_code
            if in_code:
                continue
            match = CALLOUT.match(line)
            if not match:
                continue
            text = match.group(2)
            # Join a callout that wraps onto following "> " lines.
            follow = index + 1
            while not text.endswith("*") and follow < len(lines) and lines[follow].startswith("> "):
                text += " " + lines[follow][2:]
                follow += 1
            shots.append((match.group(1), path.relative_to(DOCS).as_posix(), index + 1, text.rstrip("*").strip()))
    return shots


def render(shots):
    ids = [shot[0] for shot in shots]
    duplicates = sorted({shot_id for shot_id in ids if ids.count(shot_id) > 1})
    if duplicates:
        raise SystemExit("duplicate screenshot ids: " + ", ".join(duplicates))
    out = [
        "# Screenshot checklist",
        "",
        "Generated by `tools/docs/screenshot_checklist.py` from the",
        "`📷 Screenshot needed` callouts in `docs/`; do not edit by hand. Re-run it",
        "after adding or removing a callout.",
        "",
        "To add a screenshot:",
        "",
        "1. Capture it at 1920x1080 (or crop to the region described), with the",
        "   default **Pixel Aero Night** theme and UI scale 1x, as PNG.",
        "2. Save it as `docs/images/guide/<ID>.png`.",
        "3. Replace the callout with `![Short description](<relative path to the image>)`",
        "   followed by an italic caption line if useful.",
        "4. Re-run the script; the entry disappears from this list.",
        "",
        f"{len(shots)} screenshots needed.",
        "",
        "| ID | Page | What to capture |",
        "| --- | --- | --- |",
    ]
    for shot_id, page, line, text in shots:
        out.append(f"| `{shot_id}` | [{page}:{line}](../{page}) | {text} |")
    return "\n".join(out) + "\n"


def main():
    text = render(collect())
    if "--check" in sys.argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date; run tools/docs/screenshot_checklist.py")
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
