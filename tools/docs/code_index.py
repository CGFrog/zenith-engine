def source_files():
    output = subprocess.run(["git", "ls-files", "src"], cwd=ROOT, capture_output=True, text=True, check=True).stdout
    groups = collections.defaultdict(lambda: collections.defaultdict(set))
    for name in output.split():
        path = pathlib.PurePosixPath(name)
        if path.suffix in SOURCE_SUFFIXES:
            groups[str(path.parent)][path.stem].add(path.suffix)
    return groups


def file_summary(lines, header):
    """The first sentence of the comment block that opens the file."""
    index = 0
    if header:
        while index < len(lines) and not lines[index].startswith("#pragma once"):
            index += 1
        index += 1
    while index < len(lines) and not lines[index].strip():
        index += 1
    comment = []
    while index < len(lines) and lines[index].startswith("//"):
        comment.append(lines[index][2:].strip())
        index += 1
    text = " ".join(comment)
    # The first sentence; a period inside a name (main.cpp) is not followed by a space.
    return re.split(r"(?<=[.;])\s", text)[0] if text else ""


def describe(path):
    lines = (ROOT / path).read_text(encoding="utf-8", errors="ignore").splitlines()
    declaration = re.compile(r"^(?:class|struct|enum class)\s+(?:ZENITH_ENGINE_API\s+)?(\w+)\b[^;]*$")
    types = [match.group(1) for match in map(declaration.match, lines) if match]
    return file_summary(lines, path.endswith(".hpp")), types


def render(missing):
    groups = source_files()
    out = [BEGIN, ""]
    for directory in sorted(groups):
        out.append(f"### `{directory}/`")
        out.append("")
        purpose = DIRECTORY_PURPOSES.get(directory)
        if purpose:
            out.append(purpose)
            out.append("")
        out.append("| File | Main types | Summary |")
        out.append("| --- | --- | --- |")
        for stem in sorted(groups[directory], key=str.lower):
            suffixes = groups[directory][stem]
            primary = f"{directory}/{stem}.hpp" if ".hpp" in suffixes else f"{directory}/{stem}{sorted(suffixes)[0]}"
            summary, types = describe(primary)
            if not summary:
                missing.append(primary)
            files = "/".join(sorted(suffixes, key=SOURCE_SUFFIXES.index))
            type_list = ", ".join(f"`{name}`" for name in types[:MAX_TYPES]) + (", …" if len(types) > MAX_TYPES else "")
            out.append(f"| `{stem}` {files} | {type_list} | {summary.replace('|', '/')} |")
        out.append("")
    out.append(END)
    return "\n".join(out)


def main():
    text = CODE_MAP.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        raise SystemExit(f"{CODE_MAP} has no code-index markers")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    missing = []
    updated = head + render(missing) + tail
    for path in missing:
        print(f"{path}: no file summary (a comment opening the file)")
    if "--check" in sys.argv:
        if updated != text:
            print("docs/CODE_MAP.md's source index is out of date; run tools/docs/code_index.py")
        return 1 if updated != text or missing else 0
    CODE_MAP.write_text(updated, encoding="utf-8")
    print("updated docs/CODE_MAP.md")
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main())
