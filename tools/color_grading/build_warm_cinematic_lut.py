"""Writes assets/color_grading/warm_cinematic.cube, an example 3D colour grade.

Standard-library only. The grade works on display-encoded (sRGB) values, the
encoding the renderer applies .cube LUTs in: a gentle S-curve for contrast,
cool shadows and warm highlights, and a slight desaturation. Run from the
repository root:

    python tools/color_grading/build_warm_cinematic_lut.py
"""

import math
import pathlib

SIZE = 17
OUTPUT = pathlib.Path(__file__).resolve().parents[2] / "assets" / "color_grading" / "warm_cinematic.cube"


def contrast(value):
    # Fixed at 0, 0.5 and 1; darkens below the midpoint and brightens above it.
    return value - 0.045 * math.sin(2.0 * math.pi * value)


def grade(red, green, blue):
    red, green, blue = contrast(red), contrast(green), contrast(blue)
    luma = 0.2126 * red + 0.7152 * green + 0.0722 * blue
    shadows = (1.0 - luma) ** 2
    highlights = luma**2
    red += shadows * -0.020 + highlights * 0.045
    green += shadows * 0.008 + highlights * 0.012
    blue += shadows * 0.030 + highlights * -0.040
    saturation = 0.92
    red = luma + (red - luma) * saturation
    green = luma + (green - luma) * saturation
    blue = luma + (blue - luma) * saturation
    return tuple(min(max(channel, 0.0), 1.0) for channel in (red, green, blue))


def main():
    lines = [
        "# Example warm cinematic grade for Zenith (display-encoded sRGB in and out).",
        "# Generated by tools/color_grading/build_warm_cinematic_lut.py; edit the script, not this file.",
        'TITLE "Zenith warm cinematic"',
        f"LUT_3D_SIZE {SIZE}",
        "DOMAIN_MIN 0.0 0.0 0.0",
        "DOMAIN_MAX 1.0 1.0 1.0",
    ]
    step = 1.0 / (SIZE - 1)
    # Red varies fastest, then green, then blue.
    for blue in range(SIZE):
        for green in range(SIZE):
            for red in range(SIZE):
                graded = grade(red * step, green * step, blue * step)
                lines.append(" ".join(f"{channel:.6f}" for channel in graded))
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    with OUTPUT.open("w", encoding="ascii", newline="\n") as output:
        output.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
